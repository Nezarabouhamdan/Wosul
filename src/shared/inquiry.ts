/**
 * Contact form rules, shared by the browser and the Worker so both sides
 * always agree on what a valid inquiry is.
 */
import { isServiceId, isTimelineId, SERVICE_IDS } from './catalog.ts';
import type { Language, ServiceId, TimelineId } from './catalog.ts';

export const LIMITS = {
  fullName: { min: 2, max: 100 },
  company: { max: 160 },
  email: { max: 254 },
  context: { max: 400 },
  brief: { min: 8, max: 1800 },
} as const;

export interface Inquiry {
  fullName: string;
  company: string;
  phone: string;
  email: string;
  services: ServiceId[];
  context: string;
  brief: string;
  timeline: TimelineId | '';
  language: Language;
  /** Generated by the browser once per letter, so retries are never stored twice. */
  submissionId: string;
}

export type InquiryField = keyof Inquiry;
export type InquiryErrors = Partial<Record<InquiryField, 'invalid'>>;

export interface ValidationResult {
  valid: boolean;
  data: Inquiry;
  errors: InquiryErrors;
}

/** International (E.164) format: a plus sign, then 7 to 15 digits. */
const PHONE_PATTERN = /^\+[1-9]\d{6,14}$/;
const EMAIL_PATTERN = /^[^\s@]+@[^\s@]+\.[^\s@]+$/;
const UUID_V4_PATTERN = /^[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/i;

export function createSubmissionId(): string {
  if (typeof crypto.randomUUID === 'function') return crypto.randomUUID();
  // Fallback for browsers without randomUUID (e.g. pages served over plain http).
  const bytes = crypto.getRandomValues(new Uint8Array(16));
  bytes[6] = (bytes[6] & 0x0f) | 0x40;
  bytes[8] = (bytes[8] & 0x3f) | 0x80;
  const hex = Array.from(bytes, (byte) => byte.toString(16).padStart(2, '0')).join('');
  return `${hex.slice(0, 8)}-${hex.slice(8, 12)}-${hex.slice(12, 16)}-${hex.slice(16, 20)}-${hex.slice(20)}`;
}

function clean(value: unknown): string {
  return typeof value === 'string' ? value.trim().replace(/\r\n/g, '\n') : '';
}

/**
 * Accepts the ways people type phone numbers: Arabic-Indic or Persian digits,
 * spaces, dashes, brackets, invisible direction marks and a leading "00".
 * Example: "٠٠٩٧١ ٥٠ ١٢٣ ٤٥٦٧" becomes "+971501234567".
 */
export function normalizePhone(value: unknown): string {
  return clean(value)
    .replace(/[٠-٩۰-۹]/g, (digit) => {
      const code = digit.charCodeAt(0);
      return String(code >= 0x6f0 ? code - 0x6f0 : code - 0x660);
    })
    .replace(/[\s().\-‎‏‪-‮⁦-⁩]/g, '')
    .replace(/^00/, '+');
}

export function isValidPhone(value: unknown): boolean {
  return PHONE_PATTERN.test(normalizePhone(value));
}

export function validateInquiry(input: Record<string, unknown>): ValidationResult {
  const services = Array.isArray(input.services) ? [...new Set(input.services)] : [];
  const timeline = clean(input.timeline);
  const data: Inquiry = {
    fullName: clean(input.fullName),
    company: clean(input.company),
    phone: normalizePhone(input.phone),
    email: clean(input.email),
    services: services.filter(isServiceId),
    context: clean(input.context),
    brief: clean(input.brief),
    timeline: isTimelineId(timeline) ? timeline : '',
    language: input.language === 'en' ? 'en' : 'ar',
    submissionId: clean(input.submissionId),
  };

  const errors: InquiryErrors = {};
  const { fullName, company, email, context, brief } = LIMITS;
  if (data.fullName.length < fullName.min || data.fullName.length > fullName.max) errors.fullName = 'invalid';
  if (data.company.length > company.max) errors.company = 'invalid';
  if (!PHONE_PATTERN.test(data.phone)) errors.phone = 'invalid';
  if (data.email && (data.email.length > email.max || !EMAIL_PATTERN.test(data.email))) errors.email = 'invalid';
  if (!services.length || services.length > SERVICE_IDS.length || !services.every(isServiceId)) {
    errors.services = 'invalid';
  }
  if (data.context.length > context.max) errors.context = 'invalid';
  if (data.brief.length < brief.min || data.brief.length > brief.max) errors.brief = 'invalid';
  if (timeline && !isTimelineId(timeline)) errors.timeline = 'invalid';
  if (!UUID_V4_PATTERN.test(data.submissionId)) errors.submissionId = 'invalid';

  return { valid: Object.keys(errors).length === 0, data, errors };
}
